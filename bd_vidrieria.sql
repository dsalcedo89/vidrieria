-- =====================================================
-- 1. TABLA DE ROLES
-- =====================================================
CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =====================================================
-- 2. TABLA DE USUARIOS
-- =====================================================
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellidos VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP
);

-- =====================================================
-- 3. RELACIÓN ENTRE USUARIOS Y ROLES
-- =====================================================
CREATE TABLE usuario_roles (
    usuario_id BIGINT NOT NULL,
    rol_id BIGINT NOT NULL,

    PRIMARY KEY (usuario_id, rol_id),

    CONSTRAINT fk_usuario_roles_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id),

    CONSTRAINT fk_usuario_roles_rol
        FOREIGN KEY (rol_id)
        REFERENCES roles(id)
);

-- =====================================================
-- 4. TABLA DE PRODUCTOS
-- =====================================================
CREATE TABLE productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    categoria VARCHAR(100) NOT NULL,
    precio DECIMAL(12, 2) NOT NULL CHECK (precio >= 0),
    stock DECIMAL(12, 2) NOT NULL DEFAULT 0 CHECK (stock >= 0),
    unidad_medida VARCHAR(30) NOT NULL DEFAULT 'm2',
    imagen_url VARCHAR(500),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP
);

-- =====================================================
-- 5. TABLA DE COTIZACIONES
-- =====================================================
CREATE TABLE cotizaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(30) NOT NULL UNIQUE,
    nombre_cliente VARCHAR(150) NOT NULL,
    email_cliente VARCHAR(150),
    telefono_cliente VARCHAR(30),
    descripcion TEXT NOT NULL,
    ancho DECIMAL(10, 2),
    alto DECIMAL(10, 2),
    cantidad INTEGER NOT NULL DEFAULT 1 CHECK (cantidad > 0),
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',
    observaciones TEXT,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP
);

-- =====================================================
-- 6. TABLA DE AUDITORÍA
-- =====================================================
CREATE TABLE auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    accion VARCHAR(100) NOT NULL,
    entidad VARCHAR(100) NOT NULL,
    entidad_id VARCHAR(100),
    detalle TEXT,
    direccion_ip VARCHAR(45),
    fecha_evento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_auditoria_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
        ON DELETE SET NULL
);

-- =====================================================
-- 7. ÍNDICES
-- =====================================================
CREATE INDEX idx_productos_categoria
    ON productos(categoria);

CREATE INDEX idx_productos_activo
    ON productos(activo);

CREATE INDEX idx_cotizaciones_estado
    ON cotizaciones(estado);

CREATE INDEX idx_cotizaciones_fecha
    ON cotizaciones(fecha_creacion);

CREATE INDEX idx_auditoria_usuario
    ON auditoria(usuario_id);

CREATE INDEX idx_auditoria_fecha
    ON auditoria(fecha_evento);

